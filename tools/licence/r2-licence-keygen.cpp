//------------------------------------------------------------------------
// r2-licence-keygen - make the Ed25519 signing keypair. Run ONCE.
//
//   r2-licence-keygen --seed licence-dev/dev-signing-seed.hex
//                     --header source/LicencePublicKey.h [--dev] [--force]
//
// Writes the PRIVATE seed (64 hex chars, mode 0600) and a C++ header
// holding the PUBLIC key for the plugins to compile in. Refuses to
// overwrite an existing seed without --force: a new keypair orphans every
// key made with the old one.
//
// --header-only re-derives the header from an existing seed.
//------------------------------------------------------------------------

#include "LicenceIssue.h"

#include "monocypher.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <ctime>
#include <fstream>
#include <sstream>
#include <string>
#include <sys/stat.h>

#if defined(__APPLE__)
#include <stdlib.h>  // arc4random_buf
#endif

using namespace R2Licence;

namespace {

bool randomBytes (uint8_t* out, size_t size)
{
#if defined(__APPLE__)
	arc4random_buf (out, size);
	return true;
#else
	FILE* f = std::fopen ("/dev/urandom", "rb");
	if (!f)
		return false;
	bool ok = std::fread (out, 1, size, f) == size;
	std::fclose (f);
	return ok;
#endif
}

bool fileExists (const std::string& path)
{
	struct stat st;
	return stat (path.c_str (), &st) == 0;
}

void usage ()
{
	std::fprintf (stderr,
	              "usage: r2-licence-keygen --seed FILE --header FILE [--dev] [--force]\n"
	              "       r2-licence-keygen --seed FILE --header FILE --header-only [--dev]\n");
	std::exit (2);
}

} // namespace

int main (int argc, char** argv)
{
	std::string seedPath, headerPath;
	bool force = false, dev = false, headerOnly = false;
	for (int i = 1; i < argc; ++i)
	{
		std::string a = argv[i];
		if (a == "--seed" && i + 1 < argc) seedPath = argv[++i];
		else if (a == "--header" && i + 1 < argc) headerPath = argv[++i];
		else if (a == "--force") force = true;
		else if (a == "--dev") dev = true;
		else if (a == "--header-only") headerOnly = true;
		else usage ();
	}
	if (seedPath.empty () || headerPath.empty ())
		usage ();

	uint8_t seed[kSeedSize];
	if (headerOnly)
	{
		std::ifstream in (seedPath);
		std::stringstream ss;
		ss << in.rdbuf ();
		if (!in || !fromHex (ss.str (), seed, kSeedSize))
		{
			std::fprintf (stderr, "error: can't read a 64-hex-character seed from %s\n", seedPath.c_str ());
			return 1;
		}
	}
	else
	{
		if (fileExists (seedPath) && !force)
		{
			std::fprintf (stderr,
			              "error: %s already exists. A new keypair invalidates every key made with\n"
			              "the old one. Use --force if that is really what you want, or\n"
			              "--header-only to rebuild the header from it.\n",
			              seedPath.c_str ());
			return 1;
		}
		if (!randomBytes (seed, kSeedSize))
		{
			std::fprintf (stderr, "error: no random source\n");
			return 1;
		}
		umask (077);
		std::ofstream out (seedPath, std::ios::trunc);
		out << toHex (seed, kSeedSize) << "\n";
		out.close ();
		if (!out)
		{
			std::fprintf (stderr, "error: can't write %s (does its folder exist?)\n", seedPath.c_str ());
			return 1;
		}
		chmod (seedPath.c_str (), 0600);
	}

	uint8_t pub[kPublicKeySize];
	publicKeyFromSeed (seed, pub);
	crypto_wipe (seed, sizeof (seed));

	char date[32];
	std::time_t now = std::time (nullptr);
	std::strftime (date, sizeof (date), "%Y-%m-%d", std::gmtime (&now));

	std::ostringstream h;
	h << "//------------------------------------------------------------------------\n"
	  << "// R2Project licence - PUBLIC verification key. GENERATED by\n"
	  << "// tools/licence/r2-licence-keygen on " << date << " - don't edit by hand.\n"
	  << "//\n";
	if (dev)
		h << "// *** DEVELOPMENT KEY *** Keys signed with it stop working when the\n"
		  << "// production keypair replaces it. Never ship a release with this key.\n";
	else
		h << "// PRODUCTION KEY. Replacing it invalidates every licence ever sold.\n";
	h << "//\n"
	  << "// Public key (hex): " << toHex (pub, kPublicKeySize) << "\n"
	  << "//------------------------------------------------------------------------\n\n"
	  << "#pragma once\n\n"
	  << "#include <cstdint>\n\n"
	  << "namespace R2Licence {\n\n"
	  << "constexpr bool kPublicKeyIsDevelopment = " << (dev ? "true" : "false") << ";\n\n"
	  << "constexpr uint8_t kPublicKey[32] = {\n";
	for (size_t i = 0; i < kPublicKeySize; ++i)
	{
		char b[8];
		std::snprintf (b, sizeof (b), "0x%02x", pub[i]);
		h << ((i % 8) == 0 ? "\t" : " ") << b << (i + 1 < kPublicKeySize ? "," : "") << ((i % 8) == 7 ? "\n" : "");
	}
	h << "};\n\n} // namespace R2Licence\n";

	std::ofstream hout (headerPath, std::ios::trunc);
	hout << h.str ();
	hout.close ();
	if (!hout)
	{
		std::fprintf (stderr, "error: can't write %s\n", headerPath.c_str ());
		return 1;
	}

	std::printf ("%s keypair %s\n  private seed: %s  (KEEP SECRET, never commit)\n  public key:   %s\n  header:       %s\n",
	             dev ? "Development" : "Production", headerOnly ? "header rebuilt" : "created", seedPath.c_str (),
	             toHex (pub, kPublicKeySize).c_str (), headerPath.c_str ());
	return 0;
}
